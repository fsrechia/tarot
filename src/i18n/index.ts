export const messages: Record<Locale, Record<MessageKey, string>> = { en, 'pt-BR': ptBR };

export function translate(locale: Locale, key: MessageKey, params: Record<string, string | number> = {}): string {
  const template = messages[locale]?.[key] ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`));
}

/** Picks a localized string, falling back to English. */
export function pick(locale: Locale, text: Localized | undefined): string {
  if (!text) return '';
  return text[locale] ?? text.en;
}

export function pickList(locale: Locale, text: ({ en: string[] } & Partial<Record<Locale, string[]>>) | undefined): string[] {
  if (!text) return [];
  return text[locale] ?? text.en;
}

export function detectLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en';
  const lang = (navigator.language || 'en').toLowerCase();
  return lang.startsWith('pt') ? 'pt-BR' : 'en';
}
